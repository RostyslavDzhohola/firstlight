# Portus town: turn pack.py's town.json and pack_report.json into the shipped data.
#
#   python3 -I gen_town.py <packed dir> <client asset dir> <shared ts file>
#
# Writes <shared ts file> (packages/shared/src/content/portusTown.ts: the prefab table with collider
# solids, the layout and the ground features; read by the server and the client) and
# <client asset dir>/manifest.json (shipped files with sizes and SHA-256, texture layers, material
# slots, the data version). Reads only our own build output.
import hashlib, json, os, sys

packed, assets, ts_path = sys.argv[1], sys.argv[2], sys.argv[3]
town_raw = open(os.path.join(packed, "town.json"), "rb").read()
town = json.loads(town_raw)
report = json.load(open(os.path.join(packed, "pack_report.json")))
version = hashlib.sha256(town_raw).hexdigest()[:16]


def num(v, nd=3):
    r = round(float(v), nd)
    if r == 0:
        r = 0.0
    s = repr(r)
    return s[:-2] if s.endswith(".0") else s


def pt(p):
    return f"[{num(p[0])}, {num(p[1])}]"


names = [p["name"] for p in town["prefabs"]]
index = {n: i for i, n in enumerate(names)}
L = []
L.append("// GENERATED by tools/blender/portus/gen_town.py from the packed town (build.sh). Do not edit by hand:")
L.append("// change tools/blender/portus/build.py or pack.py and rebuild. The client's portus.glb carries the")
L.append("// same version (apps/client/public/assets-dev/portus/manifest.json).")
L.append("//")
L.append("// Town frame (planet/town.ts): east/north metres at the Portus pole, geodesic (arc-length) offsets")
L.append("// like content/places.ts offsetDir; yaw in degrees, counter-clockwise seen from above, 0 = the")
L.append("// prefab's front faces south. Prefab-local solids: x right, z front, y up from the base.")
L.append("")
L.append(f'export const PORTUS_TOWN_VERSION = "{version}";')
L.append("")
L.append("/** building: LOD1 roof shells; tree: LOD1 crossed cards; prop/static: one LOD. */")
L.append('export type TownPrefabClass = "building" | "tree" | "prop" | "static";')
L.append("")
L.append("/** A collider solid: shape 0 = box (half extents hx, hz), 1 = upright cylinder (radius hx); centre")
L.append(" * (cx, cz) and base-relative span y0..y1 in the prefab frame; yaw (degrees, CCW from above). */")
L.append("export type TownSolid = readonly [shape: 0 | 1, cx: number, cz: number, hx: number, hz: number, y0: number, y1: number, yaw: number];")
L.append("")
L.append("export interface TownPrefab {")
L.append("  name: string;")
L.append("  cls: TownPrefabClass;")
L.append("  /** Triangles at LOD0 and LOD1 (0: no LOD1). */")
L.append("  tris: readonly [number, number];")
L.append("  /** Top above the base and horizontal bound radius (m, scale 1). */")
L.append("  height: number;")
L.append("  radius: number;")
L.append("  solids: readonly TownSolid[];")
L.append("}")
L.append("")
L.append("export const TOWN_PREFABS: readonly TownPrefab[] = [")
for p in town["prefabs"]:
    solids = ", ".join("[" + ", ".join([str(int(s[0]))] + [num(v) for v in s[1:]]) + "]" for s in p["solids"])
    L.append(f'  {{ name: "{p["name"]}", cls: "{p["cls"]}", tris: [{p["tris"][0]}, {p["tris"][1]}], height: {num(p["height"], 2)}, radius: {num(p["radius"], 2)}, solids: [{solids}] }},')
L.append("];")
L.append("")
L.append("/** Placed prefabs: [prefab index, east, north, yaw, scale]. */")
L.append("export type TownItem = readonly [prefab: number, east: number, north: number, yaw: number, scale: number];")
L.append("")
L.append("export const TOWN_LAYOUT: readonly TownItem[] = [")
row = []
for it in town["layout"]:
    row.append(f'[{index[it["prefab"]]}, {num(it["east"])}, {num(it["north"])}, {num(it["yaw"], 2)}, {num(it.get("scale", 1.0))}]')
    if len(row) == 6:
        L.append("  " + ", ".join(row) + ",")
        row = []
if row:
    L.append("  " + ", ".join(row) + ",")
L.append("];")
L.append("")
L.append("/** Paved ground (no grass, no natural props): street centre lines with their widths, areas, the")
L.append(" * plaza disc and the portal court floors. Render-only (grass and prop masks). */")
L.append("export const TOWN_STREETS: readonly { name: string; width: number; pts: readonly (readonly [number, number])[] }[] = [")
for s in town["streets"]:
    L.append(f'  {{ name: "{s["name"]}", width: {num(s["width"])}, pts: [{", ".join(pt(p) for p in s["pts"])}] }},')
L.append("];")
L.append("export const TOWN_AREAS: readonly { name: string; poly: readonly (readonly [number, number])[] }[] = [")
for a in town["areas"]:
    L.append(f'  {{ name: "{a["name"]}", poly: [{", ".join(pt(p) for p in a["poly"])}] }},')
L.append("];")
L.append(f'export const TOWN_PLAZA_PAVED = {num(town["plaza"]["paved"])};')
L.append(f'export const TOWN_PORTAL_FLOOR = {num(town["portal_floor"])};')
L.append("/** The fixed features the layout was validated against (east, north). */")
L.append("export const TOWN_FIXED = {")
L.append("  portals: { " + ", ".join(f'{k}: {pt(v)}' for k, v in town["portals"].items()) + " },")
L.append(f'  juno: {pt(town["juno"])},')
L.append(f'  plaque: {pt(town["plaque"])},')
L.append(f'  dummies: [{", ".join(pt(d) for d in town["dummies"])}],')
L.append("} as const;")
L.append("")
os.makedirs(os.path.dirname(ts_path), exist_ok=True)
with open(ts_path, "w") as f:
    f.write("\n".join(L))

files = {}
for key, name in (("glb", "portus.glb"), ("color", "portus_color.webp"), ("normal", "portus_normal.webp")):
    data = open(os.path.join(assets, name), "rb").read()
    files[key] = {"name": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
lod0 = sum(report["prefabs"][it["prefab"]]["lod0"] for it in town["layout"])
manifest = {
    "version": version,
    "files": files,
    "layerSize": 512,
    "layers": report["layers"],
    "slots": report["slotTable"],
    "prefabs": len(names),
    "items": len(town["layout"]),
    "trianglesLod0": lod0,
}
with open(os.path.join(assets, "manifest.json"), "w") as f:
    json.dump(manifest, f, indent=1)
total = sum(v["bytes"] for v in files.values()) + os.path.getsize(os.path.join(assets, "manifest.json"))
print(f"gen_town: version {version}, {len(names)} prefabs, {len(town['layout'])} items, {lod0} LOD0 triangles, {total} bytes shipped")
