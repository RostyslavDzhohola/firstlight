# Writes packages/shared/src/content/wildSitePrefabs.ts from the build's sites.json (build.sh runs it).
import json, sys, hashlib
src, glb_dir, out = sys.argv[1], sys.argv[2], sys.argv[3]
data = json.load(open(src))
h = hashlib.sha256()
for body in ("arcadia", "hollowmere", "meridian"):
    h.update(open(f"{glb_dir}/sites_{body}.glb", "rb").read())
h.update(json.dumps(data, sort_keys=True).encode())
version = h.hexdigest()[:16]
def num(x):
    return repr(round(x, 3)).rstrip("0").rstrip(".") if isinstance(x, float) and x != int(x) else str(int(x)) if float(x) == int(x) else repr(x)
def arr(a):
    return "[" + ", ".join(arr(x) if isinstance(x, list) else num(x) for x in a) + "]"
lines = [
    "// GENERATED by tools/blender/sites/gen_sites.py from the Blender build (tools/blender/sites/build.sh). Do not",
    "// edit by hand: change tools/blender/sites/build_sites.py and rebuild. The client's site GLBs",
    "// (apps/client/public/assets-dev/sites/sites_<body>.glb) come from the same build; `version` hashes both.",
    "//",
    "// Prefab frame (like the outposts'): x right, z front (the front faces south at yaw 0), y up from the base.",
    "// Solids are TownSolids ([shape 0 box | 1 cylinder, cx, cz, hx, hz, y0, y1, yaw°]); `chest`, `guards` are",
    "// [x, z] spots; `lookout` is [x, z, y]; `foot` is how far the solids reach from the origin (m); `radius`",
    "// and `height` bound the mesh; `tris` = [LOD0, LOD1, glow].",
    "",
    "import type { TownSolid } from \"./portusTown.ts\";",
    "",
    "export interface WildSitePrefab {",
    "  name: string;",
    "  tris: readonly [number, number, number];",
    "  height: number;",
    "  radius: number;",
    "  foot: number;",
    "  solids: readonly TownSolid[];",
    "  chest: readonly [number, number];",
    "  guards: readonly (readonly [number, number])[];",
    "  lookout: readonly [number, number, number];",
    "}",
    "",
    f"export const WILD_SITE_PREFABS_VERSION = \"{version}\";",
    "",
    "export const WILD_SITE_PREFABS: readonly WildSitePrefab[] = [",
]
for p in data["prefabs"]:
    lines.append("  {")
    lines.append(f"    name: \"{p['name']}\", tris: {arr(p['tris'])}, height: {num(p['height'])}, radius: {num(p['radius'])}, foot: {num(p['foot'])},")
    lines.append(f"    chest: {arr(p['chest'])}, lookout: {arr(p['lookout'])},")
    lines.append(f"    guards: [{', '.join(arr(g) for g in p['guards'])}],")
    lines.append("    solids: [")
    for s in p["solids"]:
        lines.append(f"      {arr(s)},")
    lines.append("    ],")
    lines.append("  },")
lines.append("];")
lines.append("")
lines.append("export const WILD_SITE_PREFAB_BY_NAME: ReadonlyMap<string, WildSitePrefab> = new Map(WILD_SITE_PREFABS.map((p) => [p.name, p]));")
lines.append("")
open(out, "w").write("\n".join(lines))
print("wrote", out, "version", version)
