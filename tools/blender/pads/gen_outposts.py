# Pad outposts: turn the packed sites (pack.py site.json, pack_report.json) and the shipped files into
# the shared data and the client manifests.
#
#   python3 -I gen_outposts.py <packed dir> <ship dir> <shared ts file>
#
# <packed dir>/<body>/site.json and pack_report.json; <ship dir>/<body>/ holds the shipped files
# (<body>.glb and, for Meridian, its strips; Arcadia and Hollowmere reference the Portus town's strips,
# <ship dir>/../portus/ or the installed apps/client/public/assets-dev/portus/). Writes
# <shared ts file> (packages/shared/src/content/padOutposts.ts) and <ship dir>/<body>/manifest.json.
# Reads only our own build output.
import hashlib, json, os, sys

packed, ship, ts_path = sys.argv[1], sys.argv[2], sys.argv[3]
portus_dir = sys.argv[4] if len(sys.argv) > 4 else os.path.join(os.path.dirname(os.path.abspath(ship)), "portus")
BODIES = ("arcadia", "hollowmere", "meridian")
# A lighter albedo floor for the dusk body's town materials (linear): silhouettes read at dusk.
LOOK = {"arcadia": {"albedoFloor": 0.0}, "hollowmere": {"albedoFloor": 0.045}, "meridian": {"albedoFloor": 0.0}}


def num(v, nd=3):
    r = round(float(v), nd)
    if r == 0:
        r = 0.0
    s = repr(r)
    return s[:-2] if s.endswith(".0") else s


def pt(p):
    return f"[{num(p[0])}, {num(p[1])}]"


def fileinfo(path, name):
    data = open(path, "rb").read()
    return {"name": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}


L = []
L.append("// GENERATED by tools/blender/pads/gen_outposts.py from the packed sites (build.sh). Do not edit by")
L.append("// hand: change tools/blender/pads/design.py or pack.py and rebuild. Each body's asset manifest")
L.append("// (apps/client/public/assets-dev/outposts/<body>/manifest.json) carries the same version, and the")
L.append("// client refuses a manifest from another one.")
L.append("//")
L.append("// Site frame (planet/sites.ts): pad 0's tangent frame (content/places.ts tangentFrame: north = +Z")
L.append("// projected, east = north x up); east/north are geodesic metres from the pad centre, like the Portus")
L.append("// town's. Yaw in degrees, counter-clockwise seen from above, 0 = the prefab's front faces south.")
L.append("// `base` is the item's base height above the body radius, baked by the design build from the")
L.append("// terrain under its footprint (plinths and foundations take up the slope).")
L.append("")
L.append('import type { TownPrefab } from "./portusTown.ts";')
L.append("")
L.append("export type OutpostBody = \"arcadia\" | \"hollowmere\" | \"meridian\";")
L.append("")
L.append("/** A placed prefab: [prefab index, east, north, yaw, scale, base height above the radius]. */")
L.append("export type OutpostItem = readonly [prefab: number, east: number, north: number, yaw: number, scale: number, base: number];")
L.append("")
L.append("export interface OutpostSite {")
L.append("  body: OutpostBody;")
L.append("  /** Layout version (the manifest must carry the same). */")
L.append("  version: string;")
L.append("  prefabs: readonly TownPrefab[];")
L.append("  /** Pad 0's outpost (its pad platform and portal gate included). */")
L.append("  layout: readonly OutpostItem[];")
L.append("  /** Paved paths: centre lines with widths (render-only: grass and prop masks). */")
L.append("  paths: readonly { width: number; pts: readonly (readonly [number, number])[] }[];")
L.append("  /** The landing platform drawn on every other pad (visual only: no solids) and the waystone beside it. */")
L.append("  pad: number;")
L.append("  waystone: number;")
L.append("}")
L.append("")
L.append("/** Where the waystone stands at pads 1..n, in each pad's tangent frame: [east, north, yaw]. */")
L.append("export const WAYSTONE_AT = [0, -9.6, 180] as const;")
L.append("")
L.append("export const OUTPOSTS: Readonly<Record<OutpostBody, OutpostSite>> = {")
for b in BODIES:
    raw = open(os.path.join(packed, b, "site.json"), "rb").read()
    site = json.loads(raw)
    report = json.load(open(os.path.join(packed, b, "pack_report.json")))
    version = hashlib.sha256(raw).hexdigest()[:16]
    names = [p["name"] for p in site["prefabs"]]
    index = {n: i for i, n in enumerate(names)}
    L.append(f"  {b}: {{")
    L.append(f'    body: "{b}",')
    L.append(f'    version: "{version}",')
    L.append("    prefabs: [")
    for p in site["prefabs"]:
        solids = ", ".join("[" + ", ".join([str(int(s[0]))] + [num(v) for v in s[1:]]) + "]" for s in p["solids"])
        L.append(f'      {{ name: "{p["name"]}", cls: "{p["cls"]}", tris: [{p["tris"][0]}, {p["tris"][1]}], height: {num(p["height"], 2)}, radius: {num(p["radius"], 2)}, solids: [{solids}] }},')
    L.append("    ],")
    L.append("    layout: [")
    for it in site["layout"]:
        L.append(f'      [{index[it["prefab"]]}, {num(it["east"])}, {num(it["north"])}, {num(it["yaw"], 2)}, {num(it.get("scale", 1.0))}, {num(it["base"])}], // {it["label"]}')
    L.append("    ],")
    L.append("    paths: [")
    for pa in site["paths"]:
        L.append(f'      {{ width: {num(pa["width"])}, pts: [{", ".join(pt(p) for p in pa["pts"])}] }}, // {pa["name"]}')
    L.append("    ],")
    L.append(f'    pad: {site["pad"]},')
    L.append(f'    waystone: {site["waystone"]},')
    L.append("  },")

    # manifest
    d = os.path.join(ship, b)
    files = {"glb": fileinfo(os.path.join(d, f"{b}.glb"), f"{b}.glb")}
    if report["sharedStrips"]:
        files["color"] = fileinfo(os.path.join(portus_dir, "portus_color.webp"), "../portus/portus_color.webp")
        files["normal"] = fileinfo(os.path.join(portus_dir, "portus_normal.webp"), "../portus/portus_normal.webp")
    else:
        files["color"] = fileinfo(os.path.join(d, f"{b}_color.webp"), f"{b}_color.webp")
        files["normal"] = fileinfo(os.path.join(d, f"{b}_normal.webp"), f"{b}_normal.webp")
    lod0 = sum(report["prefabs"][it["prefab"]]["lod0"] for it in site["layout"])
    manifest = {"version": version, "body": b, "files": files, "layerSize": 512, "layers": report["layers"], "slots": report["slotTable"],
                "sharedStrips": report["sharedStrips"], "look": LOOK[b], "prefabs": len(names), "items": len(site["layout"]),
                "trianglesLod0": lod0}
    with open(os.path.join(d, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=1)
    own = sum(v["bytes"] for k, v in files.items() if not v["name"].startswith("../")) + os.path.getsize(os.path.join(d, "manifest.json"))
    print(f"gen_outposts: {b} version {version}, {len(names)} prefabs, {len(site['layout'])} items, {lod0} LOD0 triangles, {own} bytes of its own")
L.append("};")
L.append("")
os.makedirs(os.path.dirname(ts_path), exist_ok=True)
with open(ts_path, "w") as f:
    f.write("\n".join(L))
