/** Starter index (STARTERS order) → portrait sprite. */
export const STARTER_PORTRAIT = ["head-hexwick", "head-ash", "head-kappa", "head-unit7"] as const;

export function itemSprite(id: string | null | undefined): string {
  return (id && ITEM_SPRITE[id]) || "chest";
}

export function portraitSprite(starter: number | null | undefined): string {
  return STARTER_PORTRAIT[starter ?? 0] ?? STARTER_PORTRAIT[0];
}

/** One crisp SVG per sprite: each colour is one path of 1-pixel-high runs. */
export function spriteSvg(name: string): string {
  const rows = SPRITES[name];
  if (!rows) throw new Error(`unknown sprite ${name}`);
  const runs = new Map<string, string[]>();
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x]!;
      let n = 1;
      while (row[x + n] === ch) n++;
      if (ch !== ".") {
        let list = runs.get(ch);
        if (!list) runs.set(ch, (list = []));
        list.push(`M${x} ${y}h${n}v1h-${n}z`);
      }
      x += n;
    }
  });
  let paths = "";
  for (const [ch, d] of runs) paths += `<path fill='${SPRITE_PALETTE[ch]}' d='${d.join("")}'/>`;
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16' shape-rendering='crispEdges'>${paths}</svg>`;
}

export function spriteUrl(name: string): string {
  return `url("data:image/svg+xml,${encodeURIComponent(spriteSvg(name))}")`;
}

let installed = false;

/** Add `.px-<name> { --i: url(…) }` rules for every sprite (idempotent). Use with `<i class="px px-coin">`. */
export function installSprites(doc: Document = document): void {
  if (installed) return;
  installed = true;
  const style = doc.createElement("style");
  style.dataset.flSprites = "";
  style.textContent = Object.keys(SPRITES).map((n) => `.px-${n}{--i:${spriteUrl(n)}}`).join("\n");
  doc.head.appendChild(style);
}
